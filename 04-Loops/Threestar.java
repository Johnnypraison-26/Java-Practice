//2) Single for loop
//3*3 star pattern
class Threestar {
    public static void main(String[] args) {
        for(int i=1;i<10;i++){
            if(i%3==0){
                System.out.print("*");
                System.out.println();
            }else{
                System.out.print("*");
            }
        }
    }
}
